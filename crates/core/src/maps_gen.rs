//! Port of `src/core/game/Maps.gen.ts`.
//!
//! A pure-data module: it exports the `GameMapType` string enum (127 members,
//! value = the canonical wire name), the `mapCategoryOrder` display order
//! (16 categories), and the `maps` table (127 `MapInfo` records). There is no
//! algorithm to transcribe — the port is the data itself, plus a `run_op`
//! serialiser that lets the golden vectors pin every field bit-for-bit.
//!
//! Faithfulness notes:
//!
//! * The TS `type` field references `GameMapType.<Key>`, so its value is the
//!   enum *value* string, which may differ from the `id` (the enum *key*):
//!   e.g. `Guanabara` → `"Rio de Janeiro"`, `Tourney1` → `"Tourney 2 Teams"`.
//!   The `GAME_MAP_TYPES` table keeps both spellings so the `name ↔ value`
//!   round-trip is observable.
//! * Optional `MapInfo` fields (`featuredRank`, `specialTeamCount`,
//!   `disabledModifiers`, `forcedModifiers`, `themes`, `customTribes`,
//!   `layers`) are modelled as `Option`; the serialiser emits an explicit
//!   presence flag before each so `-1` frequencies (a real value) never
//!   collide with "absent".
//! * `CustomTribe.coordinates` is a `[number, number]` tuple; it is `None`
//!   when the TS object omits it. `MapLayer.nukeable` is likewise optional.
//! * The data table is generated from the TS source by
//!   `tools/gen_maps_rs.mjs` (the region between the `BEGIN/END GENERATED`
//!   markers); rerun that script after an upstream `Maps.gen.ts` change.

