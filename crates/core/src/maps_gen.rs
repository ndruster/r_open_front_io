// ---------------------------------------------------------------- vectors op
//
// A flat `f64` token runner shared by the golden replay and the wasm probe.
// Strings cross as `[len, u0, .. u(len-1)]` (UTF-16 code units).
//
//   kind 0 — dump `maps`: `[count, (record)*count]`.
//   kind 1 — dump `GameMapType`: `[count, (name, value)*count]`.
//   kind 2 — dump `mapCategoryOrder`: `[count, (category)*count]`.
//   kind 3 — find a map by id: `[id]` → `[0, record]` on hit, `[1]` on miss.
//
// A `record` is
//   id, type, translationKey, [n, cat*n],
//   multiplayerFrequency, ffaFrequency, teamFrequency, specialFrequency,
//   defaultNationCount,
//   (present, value) for featuredRank,
//   (present, value) for specialTeamCount,
//   (present, [n, str*n]) for disabledModifiers,
//   (present, [n, str*n]) for forcedModifiers,
//   (present, [n, str*n]) for themes,
//   (present, [n, (name, coordPresent, x, y)*n]) for customTribes,
//   (present, [n, (id, placement, nukePresent, nuke)*n]) for layers.

struct Cur<'a>(&'a [f64], usize);
impl<'a> Cur<'a> {
    fn f(&mut self) -> f64 {
        let v = self.0[self.1];
        self.1 += 1;
        v
    }
    fn u(&mut self) -> usize {
        self.f() as usize
    }
    fn string(&mut self) -> String {
        let len = self.u();
        let units: Vec<u16> = (0..len).map(|_| self.f() as u16).collect();
        String::from_utf16_lossy(&units)
    }
}

fn push_string(out: &mut Vec<f64>, s: &str) {
    let units: Vec<u16> = s.encode_utf16().collect();
    out.push(units.len() as f64);
    out.extend(units.iter().map(|&u| u as f64));
}

fn push_opt_num(out: &mut Vec<f64>, v: Option<f64>) {
    match v {
        Some(x) => {
            out.push(1.0);
            out.push(x);
        }
        None => out.push(0.0),
    }
}

fn push_opt_strs(out: &mut Vec<f64>, v: Option<&'static [&'static str]>) {
    match v {
        Some(list) => {
            out.push(1.0);
            out.push(list.len() as f64);
            for s in list {
                push_string(out, s);
            }
        }
        None => out.push(0.0),
    }
}

fn push_record(out: &mut Vec<f64>, m: &MapInfo) {
    push_string(out, m.id);
    push_string(out, m.type_);
    push_string(out, m.translation_key);
    out.push(m.categories.len() as f64);
    for c in m.categories {
        push_string(out, c);
    }
    out.push(m.multiplayer_frequency);
    out.push(m.ffa_frequency);
    out.push(m.team_frequency);
    out.push(m.special_frequency);
    out.push(m.default_nation_count);
    push_opt_num(out, m.featured_rank);
    push_opt_num(out, m.special_team_count);
    push_opt_strs(out, m.disabled_modifiers);
    push_opt_strs(out, m.forced_modifiers);
    push_opt_strs(out, m.themes);
    match m.custom_tribes {
        Some(tribes) => {
            out.push(1.0);
            out.push(tribes.len() as f64);
            for t in tribes {
                push_string(out, t.name);
                match t.coordinates {
                    Some((x, y)) => {
                        out.push(1.0);
                        out.push(x);
                        out.push(y);
                    }
                    None => out.push(0.0),
                }
            }
        }
        None => out.push(0.0),
    }
    match m.layers {
        Some(layers) => {
            out.push(1.0);
            out.push(layers.len() as f64);
            for l in layers {
                push_string(out, l.id);
                push_string(out, l.placement);
                match l.nukeable {
                    Some(b) => {
                        out.push(1.0);
                        out.push(if b { 1.0 } else { 0.0 });
                    }
                    None => out.push(0.0),
                }
            }
        }
        None => out.push(0.0),
    }
}

/// `kind`: see the block comment above.
pub fn run_op(kind: u8, args: &[f64]) -> Vec<f64> {
    let mut out = Vec::new();
    match kind {
        0 => {
            out.push(MAPS.len() as f64);
            for m in MAPS.iter() {
                push_record(&mut out, m);
            }
        }
        1 => {
            out.push(GAME_MAP_TYPES.len() as f64);
            for e in GAME_MAP_TYPES.iter() {
                push_string(&mut out, e.name);
                push_string(&mut out, e.value);
            }
        }
        2 => {
            out.push(MAP_CATEGORY_ORDER.len() as f64);
            for c in MAP_CATEGORY_ORDER.iter() {
                push_string(&mut out, c);
            }
        }
        _ => {
            let mut c = Cur(args, 0);
            let id = c.string();
            match MAPS.iter().find(|m| m.id == id) {
                Some(m) => {
                    out.push(0.0);
                    push_record(&mut out, m);
                }
                None => out.push(1.0),
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_sizes() {
        assert_eq!(GAME_MAP_TYPES.len(), 127);
        assert_eq!(MAP_CATEGORY_ORDER.len(), 16);
        assert_eq!(MAPS.len(), 127);
    }

    #[test]
    fn ids_match_enum_keys() {
        // Every map id is a GameMapType key, and its `type` is that key's
        // value.
        for m in MAPS.iter() {
            let e = GAME_MAP_TYPES
                .iter()
                .find(|e| e.name == m.id)
                .unwrap_or_else(|| panic!("no enum key for id {}", m.id));
            assert_eq!(e.value, m.type_, "type mismatch for {}", m.id);
        }
    }

    #[test]
    fn categories_are_known() {
        for m in MAPS.iter() {
            for c in m.categories {
                assert!(
                    MAP_CATEGORY_ORDER.contains(c),
                    "unknown category {c} on {}",
                    m.id
                );
            }
        }
    }

    #[test]
    fn run_op_find_hit_and_miss() {
        let args = {
            let mut a = Vec::new();
            let id = "Achiran";
            a.push(id.len() as f64);
            a.extend(id.encode_utf16().map(|u| u as f64));
            a
        };
        let hit = run_op(3, &args);
        assert_eq!(hit[0], 0.0);
        let miss = run_op(3, &[0.0]);
        assert_eq!(miss, vec![1.0]);
    }
}
