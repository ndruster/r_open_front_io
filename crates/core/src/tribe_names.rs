/// `getMapInfo`: find the `MapInfo` whose `type` equals the enum value.
fn get_map_info(map_type: &str) -> Option<&'static crate::maps_gen::MapInfo> {
    crate::maps_gen::MAPS.iter().find(|m| m.type_ == map_type)
}

/// The theme lookup with the capture's record-mutation overrides: `removed`
/// models `delete tribeNameThemes[name]`, `blanked` models emptying both
/// arrays.
fn lookup_theme<'a>(
    name: &str,
    removed: &[&str],
    blanked: &[&str],
) -> Option<(&'a [&'a str], &'a [&'a str])> {
    if removed.contains(&name) {
        return None;
    }
    if blanked.contains(&name) {
        return Some((&[], &[]));
    }
    THEMES.iter().find(|t| t.name == name).map(|t| (t.prefixes, t.suffixes))
}

/// `resolveTribeNameData(mapType?)`. The `console.warn` trace comes back as
/// the `Vec<String>`; `Err(())` models the missing-default throw.
pub fn resolve_tribe_name_data(
    map_type: Option<&str>,
    removed: &[&str],
    blanked: &[&str],
) -> (Vec<String>, Result<TribeNameData, ()>) {
    let mut warns: Vec<String> = Vec::new();
    if let Some(mt) = map_type {
        if let Some(info) = get_map_info(mt) {
            let theme_names: &[&str] = match info.themes {
                Some(t) if !t.is_empty() => t,
                _ => &["default"],
            };
            let mut merged_prefixes: Vec<String> = Vec::new();
            let mut merged_suffixes: Vec<String> = Vec::new();
            for theme_name in theme_names {
                match lookup_theme(theme_name, removed, blanked) {
                    None => {
                        warns.push(format!(
                            "[TribeNames] Map \"{mt}\" references unknown tribe name theme \"{theme_name}\". Skipping."
                        ));
                    }
                    Some((p, s)) => {
                        merged_prefixes.extend(p.iter().map(|x| x.to_string()));
                        merged_suffixes.extend(s.iter().map(|x| x.to_string()));
                    }
                }
            }
            // If all themes were unknown, fall back to default.
            if merged_prefixes.is_empty() || merged_suffixes.is_empty() {
                let Some((dp, ds)) = lookup_theme("default", removed, blanked) else {
                    return (warns, Err(()));
                };
                merged_prefixes.extend(dp.iter().map(|x| x.to_string()));
                merged_suffixes.extend(ds.iter().map(|x| x.to_string()));
            }
            let custom_tribes = match info.custom_tribes {
                Some(t) if !t.is_empty() => Some(t),
                _ => None,
            };
            return (
                warns,
                Ok(TribeNameData {
                    prefixes: merged_prefixes,
                    suffixes: merged_suffixes,
                    custom_tribes,
                }),
            );
        }
    }
    // No map type or map not found — use default theme.
    let Some((dp, ds)) = lookup_theme("default", removed, blanked) else {
        return (warns, Err(()));
    };
    (
        warns,
        Ok(TribeNameData {
            prefixes: dp.iter().map(|x| x.to_string()).collect(),
            suffixes: ds.iter().map(|x| x.to_string()).collect(),
            custom_tribes: None,
        }),
    )
}

// ---------------------------------------------------------------- vectors op
//
// A flat `f64` token runner shared by the golden replay and the wasm probe.
// Strings cross as `[len, u0, .. u(len-1)]` (UTF-16 code units).
//
// args: `[mapPresent, mapTypeString?, removedN, (removed)*, blankedN,
// (blanked)*]` (`mapPresent` 0 = no mapType argument).
// res: `[0, warnN, (warn)*, prefixN, (prefix)*, suffixN, (suffix)*,
// tribesPresent, tribeN, (name, coordPresent, x, y)*]` on success, `[1]`
// when the TS function throws (missing default theme).

struct Cur<'a>(&'a [f64], usize);
impl<'a> Cur<'a> {
    fn f(&mut self) -> f64 {
        let v = self.0[self.1];
        self.1 += 1;
        v
    }
    fn u(&mut self) -> usize {
        self.f() as usize
    }
    fn string(&mut self) -> String {
        let len = self.u();
        let units: Vec<u16> = (0..len).map(|_| self.f() as u16).collect();
        String::from_utf16_lossy(&units)
    }
}

fn push_string(out: &mut Vec<f64>, s: &str) {
    let units: Vec<u16> = s.encode_utf16().collect();
    out.push(units.len() as f64);
    out.extend(units.iter().map(|&u| u as f64));
}

fn push_strings(out: &mut Vec<f64>, list: &[String]) {
    out.push(list.len() as f64);
    for s in list {
        push_string(out, s);
    }
}

pub fn run_op(kind: u8, args: &[f64]) -> Vec<f64> {
    let mut out = Vec::new();
    if kind != 0 {
        return out;
    }
    let mut c = Cur(args, 0);
    let map_type = if c.u() == 1 { Some(c.string()) } else { None };
    let removed: Vec<String> = (0..c.u()).map(|_| c.string()).collect();
    let blanked: Vec<String> = (0..c.u()).map(|_| c.string()).collect();
    let removed_refs: Vec<&str> = removed.iter().map(|s| s.as_str()).collect();
    let blanked_refs: Vec<&str> = blanked.iter().map(|s| s.as_str()).collect();
    let (warns, res) = resolve_tribe_name_data(
        map_type.as_deref(),
        &removed_refs,
        &blanked_refs,
    );
    match res {
        Ok(data) => {
            out.push(0.0);
            push_strings(&mut out, &warns);
            push_strings(&mut out, &data.prefixes);
            push_strings(&mut out, &data.suffixes);
            match data.custom_tribes {
                Some(tribes) => {
                    out.push(1.0);
                    out.push(tribes.len() as f64);
                    for t in tribes {
                        push_string(&mut out, t.name);
                        match t.coordinates {
                            Some((x, y)) => {
                                out.push(1.0);
                                out.push(x);
                                out.push(y);
                            }
                            None => out.push(0.0),
                        }
                    }
                }
                None => out.push(0.0),
            }
        }
        Err(()) => out.push(1.0),
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn default_theme_when_no_map() {
        let (warns, Ok(data)) = resolve_tribe_name_data(None, &[], &[]) else {
            panic!("default theme exists");
        };
        assert!(warns.is_empty());
        assert_eq!(data.prefixes.len(), 176);
        assert_eq!(data.suffixes.len(), 66);
        assert_eq!(data.custom_tribes, None);
    }

    #[test]
    fn unknown_map_type_falls_back_to_default() {
        let (_, Ok(data)) = resolve_tribe_name_data(Some("NoSuchMap"), &[], &[])
        else {
            panic!();
        };
        assert_eq!(data.prefixes.len(), 176);
    }

    #[test]
    fn themes_merge_in_order() {
        // Achiran: europe (69/30) + scary (48/34).
        let (_, Ok(data)) = resolve_tribe_name_data(Some("Achiran"), &[], &[])
        else {
            panic!();
        };
        assert_eq!(data.prefixes.len(), 69 + 48);
        assert_eq!(data.suffixes.len(), 30 + 34);
    }

    #[test]
    fn custom_tribes_ride_through() {
        let (_, Ok(data)) = resolve_tribe_name_data(Some("Germany"), &[], &[])
        else {
            panic!();
        };
        assert!(data.custom_tribes.is_some());
    }

    #[test]
    fn unknown_theme_warns_and_skips() {
        // Aegean: europe + asia; remove europe -> one warn, asia survives.
        let (warns, Ok(data)) =
            resolve_tribe_name_data(Some("Aegean"), &["europe"], &[])
        else {
            panic!();
        };
        assert_eq!(
            warns,
            vec!["[TribeNames] Map \"Aegean\" references unknown tribe name theme \"europe\". Skipping.".to_string()]
        );
        assert_eq!(data.prefixes.len(), 72);
    }

    #[test]
    fn all_unknown_falls_back_to_default() {
        let (warns, Ok(data)) =
            resolve_tribe_name_data(Some("Aegean"), &["europe", "asia"], &[])
        else {
            panic!();
        };
        assert_eq!(warns.len(), 2);
        assert_eq!(data.prefixes.len(), 176);
    }

    #[test]
    fn blanked_prefixes_triggers_or_fallback() {
        // europe blanked (both arrays empty) -> merged empty -> default.
        let (_, Ok(data)) =
            resolve_tribe_name_data(Some("Alps"), &[], &["europe"])
        else {
            panic!();
        };
        assert_eq!(data.prefixes.len(), 176);
    }

    #[test]
    fn missing_default_throws() {
        let (_, res) = resolve_tribe_name_data(None, &["default"], &[]);
        assert!(res.is_err());
        let (_, res) =
            resolve_tribe_name_data(Some("Aegean"), &["default", "europe", "asia"], &[]);
        assert!(res.is_err());
    }
}
