//! Port of `src/core/execution/utils/TribeNames.ts`.
//!
//! `resolveTribeNameData(mapType?)` merges the tribe-name themes referenced
//! by a map's `MapInfo` (from [`crate::maps_gen`]) into a prefix/suffix pool,
//! with three observable edges: an unknown theme name logs a `console.warn`
//! and is skipped, an empty merged pool falls back to the `default` theme,
//! and a missing `default` theme throws. `customTribes` rides through when
//! the map has a non-empty list.
//!
//! Faithfulness notes:
//!
//! * The theme lookup is exact-key only (same prototype-chain exclusion as
//!   `server_list` / `asset_urls`); the JSON object's keys are the only
//!   reachable ones in the domain.
//! * The fallback condition is `mergedPrefixes.length === 0 ||
//!   mergedSuffixes.length === 0` — an *or*, so a theme with an empty
//!   prefixes array but non-empty suffixes still triggers the fallback, and
//!   the default theme's entries are then appended to whatever survived
//!   (suffixes can end up duplicated). The vectors pin this through the
//!   blanked-theme override in `run_op`.
//! * The warn message interpolates the map *type value* (the wire name), not
//!   the id: `[TribeNames] Map "${mapType}" references unknown tribe name
//!   theme "${themeName}". Skipping.`
//! * The theme table is generated from `resources/tribeNameThemes.json` by
//!   `tools/gen_maps_rs.mjs` (the region between the `BEGIN/END GENERATED`
//!   markers).
//! * `run_op` models the capture's mutation of the exported theme record:
//!   `removed` names are absent from the record (unknown-theme branch),
//!   `blanked` names exist but have empty prefix *and* suffix arrays (the
//!   or-condition edge).

